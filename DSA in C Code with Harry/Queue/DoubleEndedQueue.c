/*  Double Ended Queue (DEQueue) 
Double ended queue real life example 'ration ki dukaan' 
Queue FIFO principle
In  DEQueue , FIFO principle is not followed. 
  Queue :- 
   Insertion from  the Rear.
   Deletion From the front. 

   DEQueue 
   Insertion from the Rear or Front. 
   Deletion from the Rear or Front. 

   There are two type of DEQueue
   1.  Restricted Input.
       what we cannot do in this type:-
       Insertion from front is not allowed 
   2.  Restricted Output. 
       what we cannot do in this type:-
       Deletion  from rear is not allowed.  

DEqueue-ADT
1.Data-> same as queue
2.Operations-> 
    isEmpty() 
    isFull()
    intitalize()
    printQueue()
    enqueueFront()
    enqueueRare()
    DequeueFront()
    DequeueRare()
*/  
